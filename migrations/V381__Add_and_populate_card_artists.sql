DO $$
DECLARE
  card_table text;
BEGIN
  FOREACH card_table IN ARRAY ARRAY[
    'advanced_universe_cards', 'ally_universe_cards', 'aspects',
    'basic_universe_cards', 'battlegrounds', 'characters', 'events',
    'locations', 'missions', 'power_cards', 'special_cards',
    'teamwork_cards', 'training_cards'
  ]
  LOOP
    EXECUTE format('ALTER TABLE %I ADD COLUMN artist text', card_table);

    EXECUTE format($update$
      UPDATE %1$I AS card
      SET artist = credit.artist
      FROM card_artist_credits AS credit
      WHERE card.set = credit.set_code
        AND card.set_number = credit.collector_number
        AND (credit.required_image_path IS NULL OR card.image_path = credit.required_image_path)
    $update$, card_table);

    -- The ERB sheets do not include foil scans. Copy a base credit only when
    -- the foil has the matching collector number and uses the identical image.
    EXECUTE format($update$
      UPDATE %1$I AS foil
      SET artist = base.artist
      FROM %1$I AS base
      WHERE foil.set = 'ERB'
        AND base.set = foil.set
        AND foil.set_number = base.set_number || 'F'
        AND foil.image_path = base.image_path
        AND foil.is_foil IS TRUE
        AND base.is_foil IS FALSE
        AND foil.artist IS NULL
        AND base.artist IS NOT NULL
    $update$, card_table);
  END LOOP;
END
$$;
