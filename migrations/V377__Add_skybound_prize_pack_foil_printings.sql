  pp.printing_id, base.name, base.set, base.description, base.energy, base.combat,
  base.brute_force, base.intelligence, base.threat_level, base.special_abilities,
  pp.image_path, base.reverse_image_path, pp.collector_number, TRUE, pp.rarity
FROM skybound_prize_pack_import pp
