DO $$
DECLARE
  matched integer;
BEGIN
  SELECT COUNT(*) INTO matched
  FROM skybound_special_badges expected
  JOIN special_cards actual
    ON actual.set = 'SKY'
   AND actual.set_number = expected.set_number
   AND actual.character_name = expected.character_name
   AND actual.name = expected.name
   AND actual.is_foil = FALSE;

  IF matched <> 237 OR (SELECT COUNT(*) FROM special_cards WHERE set = 'SKY') <> 237 THEN
    RAISE EXCEPTION 'Skybound Special badge audit expected exactly 237 matching printings, found %', matched;
  END IF;

  UPDATE special_cards actual
  SET icons = expected.icons,
      value = expected.value,
      updated_at = NOW()
  FROM skybound_special_badges expected
  WHERE actual.set = 'SKY'
    AND actual.set_number = expected.set_number
    AND actual.character_name = expected.character_name
    AND actual.name = expected.name
    AND actual.is_foil = FALSE
    AND (actual.icons IS DISTINCT FROM expected.icons OR actual.value IS DISTINCT FROM expected.value);

  IF EXISTS (
    SELECT 1 FROM skybound_special_badges expected
    JOIN special_cards actual ON actual.set = 'SKY' AND actual.set_number = expected.set_number
    WHERE actual.icons IS DISTINCT FROM expected.icons OR actual.value IS DISTINCT FROM expected.value
  ) THEN
    RAISE EXCEPTION 'Skybound Special badge correction failed verification';
  END IF;
END $$;
